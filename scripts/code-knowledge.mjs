// ---------- Prompt 线句子 ↔ 编号 互证匹配 ----------
// Prompt 各线"核心一句话"与编号的位置对应已被 N19/V6/I5/R5/R3/R21/M2 验证；
// 但素材作者偶有并句（N 线 20 句对 22 号），故对每个编号做全句扫描取最佳匹配，
// 用挂钩它的 T1 卡名称做互证（最长公共子串 ≥6 字），匹配成功才绑定。
function normTxt(s) {
  return s.replace(/[\s，。；：、（）()「」『』【】*/－—""]-/g, '');
}
function commonSubLen(a, b) {
  let best = 0;
  for (let i = 0; i < a.length; i++) {
    for (let j = 0; j < b.length; j++) {
      let k = 0;
      while (i + k < a.length && j + k < b.length && a[i + k] === b[j + k]) k++;
      if (k > best) best = k;
    }
  }
  return best;
}

// t1Rows: [{ name, hook }]（hook 为附录 U 挂钩列原文）
export function buildPhraseContent(promptText, t1Rows) {
  if (!promptText || !t1Rows || !t1Rows.length) return {};
  const LINES = [
    { name: '管理 / 交付线', re: /管理\s*\/\s*交付线（M1–M35）核心：\*\*\n([^\n]+)/, prefix: 'M' },
    { name: 'AI-410 数据问答线', re: /AI-410 数据问答线（N1–N22）核心：\*\*\n([^\n]+)/, prefix: 'N' },
    { name: 'AI-401 招生核验线', re: /AI-401 招生核验线（V1–V18）核心：\*\*\n([^\n]+)/, prefix: 'V' },
    { name: 'RAG 全流程线', re: /RAG 全流程线（R1–R21）核心：\*\*\n([^\n]+)/, prefix: 'R' },
    { name: '基础设施线', re: /基础设施线（I1–I14）核心：\*\*\n([^\n]+)/, prefix: 'I' }
  ];
  const out = {};
  for (const L of LINES) {
    const m = promptText.match(L.re);
    if (!m) continue;
    const phrases = m[1].split('；').map((s) => s.trim()).filter((s) => s.length > 6);
    for (const row of t1Rows) {
      const codes = (row.hook || '').split(/[\/、,，]/).map((s) => s.trim());
      for (const code of codes) {
        if (!code.startsWith(L.prefix) || CONTENT[code] || out[code]) continue;
        let best = -1, bestLen = 0;
        phrases.forEach((p, i) => {
          const len = commonSubLen(normTxt(row.name), normTxt(p));
          if (len > bestLen) { bestLen = len; best = i; }
        });
        if (best >= 0 && bestLen >= 6) {
          out[code] = {
            name: row.name,
            phrase: phrases[best],
            lineName: L.name,
            idx: best,
            summary: `${code}（${L.name}）· ${row.name}：${phrases[best]}。（面试官 Prompt ${L.name}第 ${best + 1} 条，与 T1 卡挂钩互证，详见 fullContent。）`,
            fullText: [
              `**${code} · ${row.name}**`,
              '',
              `**素材原文**（面试官 Prompt ${L.name}核心 · 第 ${best + 1} 条）：${phrases[best]}。`,
              '',
              `**定位说明**：Prompt 各线"核心"一句话序列与编号的位置对应关系已由已知挂钩验证（N19=上线硬门槛、V6=申诉通道+复核人回避、I5=审核三级串联、R5/R3/R21=K-17 挂钩、M2=教研人力合同化）；本条由挂钩它的 T1 卡「${row.name}」名称与该句内容互证匹配（最长公共子串 ≥6 字），定位可信。`,
              '',
              `**出处**：面试官Prompt_可直接复制.md · ${L.name}核心`
            ].join('\n')
          };
        }
      }
    }
  }
  return out;
}
